"""
State definition for LangGraph orchestration in Prodapt AI Operations Center.

Defines the AgentState schema shared across the supervisor router and
all specialist worker nodes:
- PolicyRAG
- NetworkAnalytics
- NetworkDiagnosticsADK
- BillingResolutionADK
- CustomerCommsCrew
"""

from typing import Annotated, Any, Dict, List, TypedDict
from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages


class AgentState(TypedDict):
    """
    Shared state across all nodes in the LangGraph orchestration flow.

    Fields:
        messages: Conversation history (append-only across nodes).
        next: The supervisor routing decision indicating which node runs next
              or 'FINISH'.
        user_query: The original question entered by the customer/staff.
        agent_context: Accumulated textual findings contributed by prior worker nodes.
        execution_trace: List of executed worker steps with names and truncated outputs:
                         [{"worker": "<name>", "output": "<truncated text>"}].
        final_response: The polished customer-ready response generated by CustomerCommsCrew.
        evidence: List of structured evidence items containing source tables/docs,
                  metric timestamps, generated SQL, citations, confidence, and limitations.
    """
    messages: Annotated[List[BaseMessage], add_messages]
    next: str
    user_query: str
    agent_context: str
    execution_trace: List[Dict[str, str]]
    final_response: str
    evidence: List[Dict[str, Any]]
